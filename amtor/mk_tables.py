"""Generate amtor_tables.inc: the CCIR 476 (SITOR/AMTOR) code tables and the
PS/2 keyboard (scan code set 2) tables for amtor.asm.

The CCIR 476 tables are copied from fldigi's NAVTEX/SITOR-B decoder
(src/navtex/navtex.cxx, code_to_ltrs / code_to_figs): a 7-bit code is sent
least significant bit first, 1 = mark (the higher tone), and every valid
code has exactly four 1s. Using fldigi's table means fldigi's SITOR-B mode
decodes this station, and the test bench checks against the same table.

    python mk_tables.py      (rewrites amtor_tables.inc)
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))

# fldigi code_to_ltrs / code_to_figs, '_' = no character
LTRS = ("________________"
        "_______J___F_CK_"
        "_______W___Y_PQ_"
        "_____G___MX_V___"
        "_______A___S_IU_"
        "___D_RE__N__ ___"
        "___Z_L___H__\n___"
        "_OB_T___\r_______")
FIGS = ("________________"
        "_______'___!_:(_"
        "_______2___6_01_"
        "_____&___./_;___"
        "_______-___\x07_87_"
        "___$_43__,__ ___"
        "___\"_)___#__\n___"
        "_9?_5___\r_______")
assert len(LTRS) == 128 and len(FIGS) == 128

C_LTRS, C_FIGS, C_ALPHA, C_BETA, C_REP, C_CH32 = 0x5A, 0x36, 0x0F, 0x33, 0x66, 0x6A
C_CR, C_LF, C_SP = 0x78, 0x6C, 0x5C


def valid(c):
    return bin(c).count('1') == 4


def ccir_tables():
    c2l = [0] * 128
    c2f = [0] * 128
    a2c = [0] * 64                      # ASCII $20-$5F
    for c in range(128):
        if not valid(c):
            continue
        for tab, out in ((LTRS, c2l), (FIGS, c2f)):
            ch = tab[c]
            if ch in '_\r\n\x07':
                continue                # CR, LF handled in code; no bell
            out[c] = ord(ch)
    for c in range(128):
        ch = LTRS[c]
        if valid(c) and ch not in '_\r\n' and 0x20 <= ord(ch) <= 0x5F:
            a2c[ord(ch) - 0x20] = c     # letters (and space): LTRS
    for c in range(128):
        ch = FIGS[c]
        if valid(c) and ch not in '_\r\n\x07 ' and 0x20 <= ord(ch) <= 0x5F:
            a2c[ord(ch) - 0x20] = c | 0x80   # figures: bit 7 = needs FIGS
    return c2l, c2f, a2c


# ---- PS/2 scan code set 2 ------------------------------------------------
K = {'F1': 0x81, 'F2': 0x82, 'F3': 0x83, 'F4': 0x84, 'F5': 0x85, 'F6': 0x86,
     'F7': 0x87, 'F8': 0x88, 'F9': 0x89, 'F10': 0x8A, 'F11': 0x8B, 'F12': 0x8C,
     'UP': 0x90, 'DOWN': 0x91, 'HOME': 0x92, 'END': 0x93}

SET2 = {   # code: (normal, shifted)
    0x1C: 'aA', 0x32: 'bB', 0x21: 'cC', 0x23: 'dD', 0x24: 'eE', 0x2B: 'fF',
    0x34: 'gG', 0x33: 'hH', 0x43: 'iI', 0x3B: 'jJ', 0x42: 'kK', 0x4B: 'lL',
    0x3A: 'mM', 0x31: 'nN', 0x44: 'oO', 0x4D: 'pP', 0x15: 'qQ', 0x2D: 'rR',
    0x1B: 'sS', 0x2C: 'tT', 0x3C: 'uU', 0x2A: 'vV', 0x1D: 'wW', 0x22: 'xX',
    0x35: 'yY', 0x1A: 'zZ',
    0x45: '0)', 0x16: '1!', 0x1E: '2@', 0x26: '3#', 0x25: '4$', 0x2E: '5%',
    0x36: '6^', 0x3D: '7&', 0x3E: '8*', 0x46: '9(',
    0x0E: '`~', 0x4E: '-_', 0x55: '=+', 0x5D: '\\|', 0x54: '[{', 0x5B: ']}',
    0x4C: ';:', 0x52: '\'"', 0x41: ',<', 0x49: '.>', 0x4A: '/?', 0x29: '  ',
    # keypad, Num Lock on
    0x70: '00', 0x69: '11', 0x72: '22', 0x7A: '33', 0x6B: '44', 0x73: '55',
    0x74: '66', 0x6C: '77', 0x75: '88', 0x7D: '99', 0x71: '..', 0x79: '++',
    0x7B: '--', 0x7C: '**',
}
SPECIAL = {0x05: 'F1', 0x06: 'F2', 0x04: 'F3', 0x0C: 'F4', 0x03: 'F5',
           0x0B: 'F6', 0x83: 'F7', 0x0A: 'F8', 0x01: 'F9', 0x09: 'F10',
           0x78: 'F11', 0x07: 'F12'}
CTRL = {0x76: 27, 0x66: 8, 0x5A: 13, 0x0D: ord(' ')}     # Esc, Backspace, Enter, Tab
# E0-prefixed keys: (code, key)
EXT = [(0x7D, 'UP'), (0x7A, 'DOWN'), (0x75, 'UP'), (0x72, 'DOWN'),
       (0x6C, 'HOME'), (0x69, 'END'), (0x5A, 13), (0x71, 8), (0x4A, ord('/'))]


def ps2_tables():
    norm = [0] * 128
    shft = [0] * 128
    for code, (a, b) in SET2.items():
        norm[code] = ord(a)
        shft[code] = ord(b)
    for code, name in SPECIAL.items():
        if code < 128:
            norm[code] = shft[code] = K[name]
    for code, v in CTRL.items():
        norm[code] = shft[code] = v
    extc = [c for c, _ in EXT]
    extk = [K[k] if isinstance(k, str) else k for _, k in EXT]
    return norm, shft, extc, extk


def rows(name, data, comment=''):
    out = ['%s:%s' % (name, ('  ; ' + comment) if comment else '')]
    for i in range(0, len(data), 16):
        out.append('        db      ' + ','.join('$%02X' % v for v in data[i:i + 16]))
    return out


def main():
    c2l, c2f, a2c = ccir_tables()
    norm, shft, extc, extk = ps2_tables()
    out = ['; amtor_tables.inc - generated by mk_tables.py, do not edit', '']
    out += ['C_LTRS          EQU     $%02X' % C_LTRS, 'C_FIGS          EQU     $%02X' % C_FIGS,
            'C_ALPHA         EQU     $%02X           ; idle alpha (phasing 2)' % C_ALPHA,
            'C_BETA          EQU     $%02X' % C_BETA,
            'C_REP           EQU     $%02X           ; RQ / phasing 1' % C_REP,
            'C_CH32          EQU     $%02X' % C_CH32,
            'C_CR            EQU     $%02X' % C_CR, 'C_LF            EQU     $%02X' % C_LF,
            'C_SP            EQU     $%02X' % C_SP, '']
    for k, v in K.items():
        out.append('K_%-13s EQU     $%02X' % (k, v))
    out.append('')
    out += rows('C2L', c2l, 'CCIR 476 code -> ASCII, letters shift (0 = none)')
    out += rows('C2F', c2f, 'CCIR 476 code -> ASCII, figures shift')
    out += rows('A2C', a2c, 'ASCII $20-$5F -> code, bit 7 = figures shift, 0 = none')
    out += rows('PS2N', norm, 'PS/2 set 2 scan code -> key')
    out += rows('PS2S', shft, 'same, with Shift held')
    out += ['EXTN            EQU     %d' % len(extc)]
    out += rows('EXTC', extc, 'E0-prefixed scan codes')
    out += rows('EXTK', extk, 'and their keys')
    path = os.path.join(HERE, 'amtor_tables.inc')
    with open(path, 'w', newline='\r\n') as f:
        f.write('\n'.join(out) + '\n')
    print('wrote', path)


if __name__ == '__main__':
    main()
